import { readFile, writeFile } from 'node:fs/promises'
import { randomBytes } from 'node:crypto'
const { chromium } = await import('file:///C:/Users/Lohith%20k/Desktop/ODOO/StockSense/frontend/node_modules/playwright-core/index.mjs')
const fixture = JSON.parse(await readFile(new URL('./phase-f-browser-fixture.json', import.meta.url), 'utf8'))
const origin = 'http://127.0.0.1:5173'
const password = randomBytes(36).toString('base64url')
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ baseURL: origin, reducedMotion: 'reduce' })
const page = await context.newPage()
try {
  await page.goto('/login?next=%2Fapp%2Fadmin')
  await page.getByLabel('Email or username', { exact: true }).fill(fixture.username)
  await page.getByLabel('Password', { exact: true }).fill(fixture.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.waitForURL('**/app/admin')
  const accounts = await (await context.request.get('/api/admin/users?limit=100')).json()
  if (accounts.some(account => account.username === 'local_admin')) throw new Error('Local administrator already exists; no changes made')
  await writeFile(new URL('./phase-f-local-admin.json', import.meta.url), JSON.stringify({ username: 'local_admin', password, origin }, null, 2))
  await page.getByLabel('Full name', { exact: true }).fill('Local Administrator')
  await page.getByLabel('Username (or supply email)', { exact: true }).fill('local_admin')
  await page.getByLabel('Initial password', { exact: true }).fill(password)
  await page.locator('form').getByRole('combobox').selectOption('admin')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'local_admin' }).waitFor()
  await context.request.post('/api/auth/logout', { headers: { Origin: origin } })
  await page.goto('/login?next=%2Fapp%2Fadmin')
  await page.getByLabel('Email or username', { exact: true }).fill('local_admin')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.waitForURL('**/app/admin')
  const disabled = await context.request.post(`/api/admin/users/${fixture.id}/deactivate`, { headers: { Origin: origin } })
  if (!disabled.ok()) throw new Error('Could not deactivate temporary admin')
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await page.getByRole('row').filter({ hasText: fixture.username }).getByRole('cell', { name: 'Inactive', exact: true }).waitFor()
  await context.request.post('/api/auth/logout', { headers: { Origin: origin } })
  console.log('PASS admin UI creation and local_admin login; temporary admin deactivated; password stored privately')
} finally { await browser.close() }
